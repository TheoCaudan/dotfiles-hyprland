hl.on("hyprland.start", function()
    hl.exec_cmd("dbus-update-activation-environment --systemd WAYLAND_DISPLAY XDG_CURRENT_DESKTOP")
    hl.exec_cmd("systemctl --user import-environment WAYLAND_DISPLAY XDG_CURRENT_DESKTOP")
    hl.exec_cmd("pkill waybar; /usr/bin/waybar")
    hl.exec_cmd("sleep 3; pkill -USR2 -x waybar")
    hl.exec_cmd("wl-paste --type text --watch cliphist store")
    hl.exec_cmd("dunst")
    hl.exec_cmd("nohup mpvpaper --auto-pause -o 'no-audio loop-file=inf hwdec=auto' '*' ~/.config/hypr/current_wallpaper >/dev/null 2>&1 &")
    hl.exec_cmd("nm-applet")
    hl.exec_cmd("blueman-applet")
    hl.exec_cmd("lxpolkit")
    hl.exec_cmd("udiskie --smart-tray --notify")
    hl.exec_cmd("foot --server")
    hl.exec_cmd("hyprctl setcursor ComixCursors-White 24")
end)
